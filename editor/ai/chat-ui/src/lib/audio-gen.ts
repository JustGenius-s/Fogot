// ─── Persisting audio ──────────────────────────────────────────────

/** Write base64 audio bytes to a res:// path and refresh any cached data URL. */
export async function saveAudioBase64(base64: string, path: string): Promise<string> {
  await bridgeRPC('write_file', { path, content: base64, binary: true })
  invalidateAsset(path)
  return path
}
